import pandas as pd
import numpy as np
import matplotlib.pyplot as plt

patientName = np.array(["Kanan", "Radhika", "Mehak"])
age = np.array([20, 22, 21])
id = np.array([101, 102, 103])
diagnosis = np.array(["Fever", "Cold", "Cough"])
temperature = np.array([102, 98, 99])

print("Health Report")
print("Patient Name: ", patientName)
print("Age: ", age)
print("ID: ", id)
print("Diagnosis: ", diagnosis)
print("Temperature: ", temperature)

data = {
    "Patient Name": patientName,
    "Age": age,
    "ID": id,
    "Diagnosis": diagnosis,
    "Temperature": temperature
}
df = pd.DataFrame(data)
print("\nPatient Data: ")
print(df)

print("Statistics:")
print(df.describe())

print("Patients with temperature > 98")
print(df[df["Temperature"] > 98])

df.to_csv("patient_data.csv", index=False)

new_df = pd.read_csv("patient_data.csv")

print("\nData Read from CSV:")
print(new_df)

plt.plot(
    df["ID"],
    df["Temperature"],
    marker="o"
)

plt.title("Temperature Analysis")
plt.xlabel("Patient ID")
plt.ylabel("Temperature")
plt.grid(True)

plt.show()

df.to_csv("patient_data.csv", index=False)

new_df = pd.read_csv("patient_data.csv")

print("\nData Read from CSV:")
print(new_df)

